// PALETTE VALIDATION
// ==========================================

function validatePalette(palette) {

    if (!Array.isArray(palette)) {
        throw new Error(
            "CRYSTAL_PALETTE must be an array."
        );
    }

    const seenCodes = new Set();

    for (const color of palette) {

        if (
            !color ||
            typeof color.code !== "string" ||
            typeof color.name !== "string" ||
            typeof color.hex !== "string"
        ) {
            throw new Error(
                "Invalid color entry in CRYSTAL_PALETTE."
            );
        }

        if (seenCodes.has(color.code)) {
            console.warn(
                `Duplicate color code detected: ${color.code}`
            );
        }

        seenCodes.add(color.code);
    }

    return true;
}


